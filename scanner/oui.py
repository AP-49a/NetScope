_HEX_CLEAN_RE = re.compile(r"[^0-9A-Fa-f]")


def normalize_mac_prefix(mac: str) -> Optional[str]:
    """
    Extract the 6-hex-digit OUI prefix from a MAC address string.

    Parameters
    ----------
    mac : str
        MAC address in any standard notation (e.g. ``'aa:bb:cc:dd:ee:ff'``,
        ``'AA-BB-CC-DD-EE-FF'``, ``'aabb.ccdd.eeff'``).

    Returns
    -------
    Optional[str]
        6-character uppercase hex string (e.g. ``'AABBCC'``), or None if
        *mac* contains fewer than 6 valid hexadecimal digits.
    """
    if not mac or not isinstance(mac, str):
        return None

    cleaned = _HEX_CLEAN_RE.sub("", mac).upper()
    if len(cleaned) < 6:
        return None

    return cleaned[:6]


def get_manufacturer(mac: Optional[str]) -> Optional[str]:
    """
    Return the hardware manufacturer name for a given MAC address.

    Parameters
    ----------
    mac : Optional[str]
        MAC address string.

    Returns
    -------
    Optional[str]
        Vendor name (e.g. ``'Apple'``, ``'Intel'``), or None if unrecognized.
    """
    if not mac:
        return None

    prefix = normalize_mac_prefix(mac)
    if not prefix:
        return None

    return _OUI_DATABASE.get(prefix)


def is_locally_administered(mac: Optional[str]) -> bool:
    """
    Check if a MAC address has the IEEE 802 Locally Administered Address (LAA) bit set.

    In modern mobile operating systems (iOS 14+, Android 10+, Windows 11), Wi-Fi
    privacy mechanisms randomize the client MAC address. The second hexadecimal
    character of a randomized MAC address is always 2, 6, A, or E (U/L bit = 1).
    """
    if not mac or not isinstance(mac, str):
        return False

    prefix = normalize_mac_prefix(mac)
    if prefix and len(prefix) >= 2:
        return prefix[1] in "26AE"

    return False
